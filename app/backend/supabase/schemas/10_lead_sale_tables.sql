-- Lead Sale relational resources. Form payloads are stored in data; generated
-- relational keys enforce references/uniqueness. No client writes are granted.
create schema if not exists private;

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id),
  first_name text not null default '', last_name text not null default '',
  email text not null, administrator boolean not null default false,
  disabled boolean not null default true
);
create table public.lead_roles (code text primary key, label text not null);
insert into public.lead_roles values ('admin','Quản trị viên'),('intake','Tiếp nhận hồ sơ'),('leader','Trưởng nhóm'),('telesale','Telesale'),('viewer','Xem báo cáo');
create table public.lead_teams (id text primary key, name text not null);
insert into public.lead_teams values ('default','Nhóm tuyển tài xế');
create table public.lead_user_roles (
  sales_id bigint primary key references public.sales(id),
  role_code text not null references public.lead_roles(code),
  team_id text not null default 'default' references public.lead_teams(id)
);
create table public.lead_statuses (code text primary key, label text not null);
insert into public.lead_statuses values ('New','Mới'),('Activated','Đã đăng ký'),('Onboarded','Đã chạy đơn đầu'),('Closed','Đã đóng');
create table public.lead_sources (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  name text generated always as (data->>'name') stored not null unique,
  check(length(btrim(name)) between 2 and 120),
  check(jsonb_typeof(data->'active')='boolean')
);
insert into public.lead_sources(data) values
('{"id":"web","name":"Form website","active":true}'),
('{"id":"facebook","name":"Facebook","active":true}'),
('{"id":"hotline","name":"Hotline","active":true}'),
('{"id":"referral","name":"Tài xế giới thiệu","active":true}');

create table public.leads (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  phone text generated always as (data->>'phone') stored not null unique,
  source_id text generated always as (data->>'sourceId') stored not null references public.lead_sources(id),
  status text generated always as (data->>'status') stored not null references public.lead_statuses(code),
  archived boolean generated always as ((data->>'archived')::boolean) stored not null,
  check(phone ~ '^0[0-9]{9}$'),
  check(length(btrim(data->>'name')) between 2 and 120),
  check(length(btrim(data->>'city')) between 1 and 120),
  check(data->>'vehicle' in ('Van','Motorbike')),
  check(jsonb_typeof(data->'tags')='array')
);
create index lead_source_status on public.leads(source_id,status);
create table public.lead_assignments (
  data jsonb not null,
  sequence bigint generated always as identity unique,
  id text generated always as (data->>'id') stored primary key,
  lead_id text generated always as (data->>'leadId') stored not null references public.leads(id),
  assignee_id bigint generated always as ((data->>'assigneeId')::bigint) stored not null references public.sales(id),
  team_id text generated always as (data->>'teamId') stored not null references public.lead_teams(id),
  status text generated always as (data->>'status') stored not null check(status in ('New','Open','Solved','Closed')),
  expires_at timestamptz not null,
  check((data->>'expiresAt')::timestamptz=expires_at)
);
create unique index lead_one_live_assignment on public.lead_assignments(lead_id) where status <> 'Closed';
create index lead_assignments_owner on public.lead_assignments(assignee_id,status,expires_at);
create index lead_assignments_lead on public.lead_assignments(lead_id);
create table public.lead_care_rounds (
  assignment_id text not null references public.lead_assignments(id),
  round_no integer not null check(round_no > 0), opened_at timestamptz not null default now(),
  actor_id bigint not null references public.sales(id), reason text not null,
  primary key(assignment_id,round_no)
);
create table public.lead_activities (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  assignment_id text generated always as (data->>'assignmentId') stored not null references public.lead_assignments(id),
  lead_id text generated always as (data->>'leadId') stored not null references public.leads(id),
  round_no integer generated always as ((data->>'round')::integer) stored not null,
  appointment_id text generated always as (data->>'appointmentId') stored unique,
  foreign key(assignment_id,round_no) references public.lead_care_rounds(assignment_id,round_no),
  check(data->>'outcome' in ('called','no_answer','overdue','wrong_phone')),
  check(data->>'decision' in ('none','agreed','declined','hungup')),
  check(data->>'reason' in ('none','no_need','busy','ineligible')),
  check(length(btrim(data->>'note'))>0)
);
create table public.lead_appointments (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  assignment_id text generated always as (data->>'assignmentId') stored not null references public.lead_assignments(id),
  lead_id text generated always as (data->>'leadId') stored not null references public.leads(id),
  status text generated always as (data->>'status') stored not null check(status in ('scheduled','attended','missed','cancelled')),
  due_at timestamptz not null,
  check((data->>'at')::timestamptz=due_at),
  check(length(btrim(data->>'place'))>0)
);
alter table public.lead_activities add constraint lead_activity_appointment_fk foreign key(appointment_id) references public.lead_appointments(id);
create unique index lead_one_scheduled_appointment on public.lead_appointments(assignment_id) where status='scheduled';
create index lead_appointments_due on public.lead_appointments(due_at) where status='scheduled';
create table public.lead_receptions (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  lead_id text generated always as (data->>'leadId') stored not null references public.leads(id),
  source_id text generated always as (data->>'sourceId') stored not null references public.lead_sources(id)
);
create table public.lead_closure_reviews (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  assignment_id text generated always as (data->>'assignmentId') stored not null unique references public.lead_assignments(id),
  lead_id text generated always as (data->>'leadId') stored not null references public.leads(id)
);
create table public.lead_notifications (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  recipient_id bigint generated always as ((data->>'recipientId')::bigint) stored not null references public.sales(id)
);
create table public.lead_attachments (
  data jsonb not null,
  id text generated always as (data->>'path') stored primary key,
  activity_id text not null references public.lead_activities(id),
  lead_id text not null references public.leads(id)
);
create table public.lead_audit_logs (
  data jsonb not null,
  id text generated always as (data->>'id') stored primary key,
  lead_id text references public.leads(id)
);
create table private.lead_requests (
  actor_id bigint not null references public.sales(id), request_id uuid not null,
  payload jsonb not null, created_at timestamptz not null default now(),
  primary key(actor_id,request_id)
);
create table private.lead_import_batches (
  id uuid primary key, actor_id bigint not null references public.sales(id),
  file_name text not null, created_at timestamptz not null default now()
);

-- Accounts created through Auth remain disabled until explicitly provisioned.
create or replace function private.lead_auth_profile() returns trigger
language plpgsql security definer set search_path = public,private as $$
begin
  insert into public.sales(user_id,email,first_name,last_name,administrator,disabled)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'name','Nhân viên'),'',false,true)
  on conflict(user_id) do update set email=excluded.email;
  return new;
end;
$$;
create trigger lead_auth_created after insert on auth.users for each row execute function private.lead_auth_profile();
